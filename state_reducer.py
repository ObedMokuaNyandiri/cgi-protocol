import copy
import json

# ---------------------------------------------------------------------------
# SAFE FIELD ALLOW-LIST
# FIX FLAW-009: The reducer is no longer hardcoded to two fields.
# Any key from the AI's output that is in _SAFE_FIELDS and has an acceptable
# type will be persisted to state. This gives the memory tree real utility.
# ---------------------------------------------------------------------------

_SAFE_FIELDS: dict[str, type] = {
    "portfolio_value":  (int, float),
    "last_trade":       str,
    "ticker":           str,
    "action":           str,
    "order_type":       str,
    "asset_class":      str,
    "risk_assessment":  str,
    "quantity":         (int, float),
    "reasoning":        str,
}

_MAX_STRING_LEN = 1024   # Prevent memory-bloat from huge string values


class StateReducer:
    """
    Robust State Reducer (RSR) v2.

    Deterministically applies an ActionPayload (generated by the LLM)
    to the Current State. The reducer is:
      - Pure functional: never mutates current_state in place.
      - Schema-enforced: only allow-listed keys with correct types are persisted.
      - Monotonic: epoch always increments, preventing rollback.
      - Livelock-safe: malformed JSON falls back gracefully; no bricking.
    """

    @staticmethod
    def reduce(current_state: dict, action_payload: str) -> dict:
        import re

        # Deep copy guarantees pure functional mutation
        new_state = copy.deepcopy(current_state)

        # Epoch is always incremented monotonically, regardless of payload validity
        new_state["epoch"] = new_state.get("epoch", 0) + 1

        try:
            # Strip <think>...</think> reasoning blocks before JSON parsing
            clean_payload = re.sub(
                r"<think>.*?</think>", "", action_payload, flags=re.DOTALL
            ).strip()

            if not clean_payload:
                raise ValueError("Empty payload after stripping reasoning blocks.")

            action = json.loads(clean_payload)

            if not isinstance(action, dict):
                raise ValueError("Action must be a JSON object (dict).")

            # Apply mutations for every safe, well-typed field
            applied = []
            for key, allowed_types in _SAFE_FIELDS.items():
                if key not in action:
                    continue
                val = action[key]

                # Type check
                if not isinstance(val, allowed_types):
                    continue

                # String length guard
                if isinstance(val, str) and len(val) > _MAX_STRING_LEN:
                    val = val[:_MAX_STRING_LEN]

                # Domain-specific range check for financial values
                if key in ("portfolio_value", "quantity"):
                    val_f = float(val)
                    if val_f < 0 or val_f > 1e12:   # 1 trillion upper bound
                        raise ValueError(
                            f"Field '{key}' value {val_f} is out of safe range."
                        )

                new_state[key] = val
                applied.append(key)

            new_state["last_error"] = None
            new_state["last_applied_fields"] = applied

        except (json.JSONDecodeError, ValueError) as e:
            # FALLBACK: Preserve all financial balances (NO-OP on portfolio).
            # Log the error so auditors can detect repeated malformed outputs.
            new_state["last_error"] = f"ParseFailed: {e!s}"
            new_state.pop("last_applied_fields", None)

        return new_state

def _compute_public_signals(previous_root: str, output_hash: str, new_root: str) -> str:
    """
    Computes the canonical public signal hash. In a real zkML setup, 
    these signals represent the boundary of the circuit.
    For the State Reducer, it proves StateReducer(previous_root, ActionPayload) == new_root.
    """
    signal_data = f"{previous_root}|{output_hash}|{new_root}"
    return hashlib.sha256(signal_data.encode("utf-8")).hexdigest()

# Set this flag to True to attempt actual EZKL Halo2 execution.
# Requires 'ezkl' installed globally and the .compiled circuit generated.
USE_REAL_CIRCUIT = os.environ.get("USE_REAL_ZK_CIRCUITS", "0") == "1"

# Paths to EZKL Artifacts generated by circuits/compile_ezkl_circuit.py
ARTIFACTS_DIR = os.path.join(os.path.dirname(__file__), "circuits", "ezkl_artifacts")
COMPILED_CIRCUIT = os.path.join(ARTIFACTS_DIR, "network.compiled")
PK_PATH = os.path.join(ARTIFACTS_DIR, "test.pk")
VK_PATH = os.path.join(ARTIFACTS_DIR, "test.vk")
SETTINGS_PATH = os.path.join(ARTIFACTS_DIR, "settings.json")


def _generate_real_proof(public_signal: str) -> dict[str, Any]:
    """
    Executes the actual Halo2 circuit via EZKL.
    Prerequisites:
    1. network.compiled must be compiled.
    2. A trusted setup ceremony (test.pk) must be present.
    """
    print("[ZK-SNARK] Executing real Halo2 proof generation via EZKL...")
    
    if ezkl is None:
        raise ImportError("ezkl module not installed. Run 'pip install ezkl'")

    if not os.path.exists(PK_PATH) or not os.path.exists(COMPILED_CIRCUIT):
        raise FileNotFoundError("EZKL artifacts missing. Run compile_ezkl_circuit.py first.")

    # Check if we are using the Windows mock fallback keys
    with open(PK_PATH, 'rb') as f:
        if b"MOCK" in f.read(10):
            print("[ZK-SNARK] Detected mock keys from compilation script fallback. Skipping actual ezkl.prove...")
            return _generate_mock_proof(public_signal)

    # In a true deployment, we would map the public_signal to the input of the neural network
    # and create an input.json file here.
    witness_path = os.path.join(ARTIFACTS_DIR, "witness.json")
    proof_path = os.path.join(ARTIFACTS_DIR, "proof.json")
    
    try:
        # Generate Witness
        # ezkl.gen_witness(data_path, COMPILED_CIRCUIT, witness_path)
        
        # Generate the ZK Proof
        res = ezkl.prove(
            witness_path,
            COMPILED_CIRCUIT,
            PK_PATH,
            proof_path,
            "evm",
            "single",
        )
        if hasattr(res, '__await__'):
            asyncio.run(res)
            
        with open(proof_path, 'r') as f:
            proof = json.load(f)
        return proof
    except (FileNotFoundError, json.JSONDecodeError, RuntimeError, SystemError) as e:
        print(f"[WARNING] ezkl.prove failed: {e}")
        return _generate_mock_proof(public_signal)


def _generate_mock_proof(public_signal: str) -> dict[str, Any]:
    # Mocking the mathematical structure of an EZKL proof
    return {
        "protocol": "halo2",
        "curve": "bn256",
        "is_mock": True,
        "proof": f"0x{hashlib.sha256((public_signal + 'proof_data').encode()).hexdigest()}",
        "instances": [
            f"0x{hashlib.sha256((public_signal + 'instance').encode()).hexdigest()}"
        ]
    }


def generate_inference_proof(previous_root: str, output_hash: str, new_root: str) -> tuple[dict[str, Any], str]:
    """
    Generates a Halo2 zero-knowledge proof for a neural network forward pass using EZKL.
    If USE_REAL_CIRCUIT is set, calls out to the EZKL rust bindings.
    Otherwise, generates a structurally sound simulated proof for testing.
    """
    public_signal = _compute_public_signals(previous_root, output_hash, new_root)
    
    if USE_REAL_CIRCUIT:
        return _generate_real_proof(public_signal), public_signal

    print("[ZK-SNARK] Simulating EZKL Halo2 neural network forward pass proof...")
    return _generate_mock_proof(public_signal), public_signal


def verify_inference_proof(proof: dict[str, Any], public_signal: str) -> bool:
    """
    Mathematically verifies the zero-knowledge proof against the public signal.
    """
    try:
        if proof.get("protocol") != "halo2":
            return False
            
        # FIX H-6: The verifier previously trusted `proof.get("is_mock")` to skip
        # actual cryptographic verification. This allowed an attacker to bypass
        # the real circuit in production by submitting a fake mock proof.
        # Now, if USE_REAL_CIRCUIT is True, we STRICTLY require a real proof and
        # reject any proof that claims to be a mock.
        if USE_REAL_CIRCUIT:
            if proof.get("is_mock"):
                print("[ZK-SNARK] REJECTED: Mock proofs are not permitted in production.")
                return False
                
            print("[ZK-SNARK] Verifying real Halo2 proof via EZKL...")
            proof_path = os.path.join(ARTIFACTS_DIR, "proof.json")
            with open(proof_path, 'w') as f:
                json.dump(proof, f)
                
            res = ezkl.verify(
                proof_path,
                SETTINGS_PATH,
                VK_PATH,
            )
            if hasattr(res, '__await__'):
                res = asyncio.run(res)
            return res

        # Fallback for testing when USE_REAL_CIRCUIT = False
        if not proof.get("is_mock"):
            print("[ZK-SNARK] REJECTED: Expected a mock proof in test mode.")
            return False

        # Re-verify the mathematical binding (Mock validation)
        expected_proof = f"0x{hashlib.sha256((public_signal + 'proof_data').encode()).hexdigest()}"
        return proof["proof"] == expected_proof
    except (KeyError, TypeError, ValueError):
        return False
